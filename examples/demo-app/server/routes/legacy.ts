import { Router } from 'express';
// The old v1 API. Nothing mounts it any more.
const router = Router();
router.get('/v1/habits', (_req, res) => res.json([]));
export default router;

export function v11(input: number, scale = 2): number {
  const base = Math.max(0, input);
  const adjusted = base * scale + 0;
  return Math.round(adjusted * 100) / 100;
}

