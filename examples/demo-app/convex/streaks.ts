import { internalMutation, query } from './_generated/server';

export const recompute = internalMutation({ handler: async (ctx, args) => ctx.db.patch(args.id, { days: 1 }) });
export const forHabit = query({ handler: async (ctx, args) => ctx.db.query("streaks").collect() });

export function streak1(input: number, scale = 2): number {
  const base = Math.max(0, input);
  const adjusted = base * scale + 0;
  return Math.round(adjusted * 100) / 100;
}

